//! Builds `.service` + `.timer` unit files from a cron request and installs them for the user.

use std::path::PathBuf;

use zbus::Connection;

use crate::cron::{self, Trigger};
use crate::models::{GeneratedTimer, TimerRequest};
use crate::systemd;

pub fn generate(req: &TimerRequest) -> Result<GeneratedTimer, String> {
    let base = req
        .unit_name
        .trim()
        .trim_end_matches(".service")
        .trim_end_matches(".timer");
    systemd::validate_unit_name(base)?;
    if base.contains('@') {
        return Err("Template units (containing '@') are not supported".into());
    }

    let exec = req.exec_path.trim();
    if !exec.starts_with('/') {
        return Err("The executable must be an absolute path (e.g. /usr/local/bin/backup.sh)".into());
    }
    let description = req
        .description
        .as_deref()
        .map(str::trim)
        .filter(|d| !d.is_empty())
        .map(str::to_string)
        .unwrap_or_else(|| format!("{base} (generated by Systemd Dashboard)"));
    for (label, v) in [("Executable", exec), ("Description", description.as_str())] {
        if v.contains(['\n', '\r']) {
            return Err(format!("{label} must be a single line"));
        }
    }

    let service_name = format!("{base}.service");
    let timer_name = format!("{base}.timer");
    let (on_calendar, trigger_lines) = match cron::parse(&req.cron)? {
        Trigger::Calendar(cal) => {
            let lines = cal.iter().map(|c| format!("OnCalendar={c}\n")).collect::<String>();
            (cal, lines + "Persistent=true\n")
        }
        // A user manager starts at login, which is the closest match to a crontab @reboot.
        Trigger::Boot => (Vec::new(), "OnStartupSec=1min\n".to_string()),
    };

    let service_content = format!(
        "[Unit]\n\
         Description={description}\n\
         \n\
         [Service]\n\
         Type=oneshot\n\
         ExecStart={exec}\n"
    );
    let timer_content = format!(
        "[Unit]\n\
         Description=Timer for {service_name} (cron: {cron})\n\
         \n\
         [Timer]\n\
         {trigger_lines}\
         Unit={service_name}\n\
         \n\
         [Install]\n\
         WantedBy=timers.target\n",
        cron = req.cron.trim(),
    );

    Ok(GeneratedTimer {
        service_name,
        timer_name,
        service_content,
        timer_content,
        on_calendar,
        next_runs: Vec::new(),
    })
}

/// Asks `systemd-analyze calendar` for upcoming elapse times (best-effort preview).
pub async fn next_runs(on_calendar: &[String]) -> Vec<String> {
    if on_calendar.is_empty() {
        return Vec::new();
    }
    let Ok(out) = tokio::process::Command::new("systemd-analyze")
        .args(["calendar", "--iterations=5"])
        .args(on_calendar)
        .output()
        .await
    else {
        return Vec::new();
    };
    let mut runs: Vec<String> = String::from_utf8_lossy(&out.stdout)
        .lines()
        .filter_map(|l| {
            let (key, value) = l.split_once(": ")?;
            let key = key.trim();
            (key == "Next elapse" || key.starts_with("Iter. #")).then(|| value.trim().to_string())
        })
        .collect();
    // Entries look like "Mon 2026-10-26 02:00:00 +0530"; sort on the part after the weekday.
    runs.sort_by(|a, b| a.split_once(' ').map(|x| x.1).cmp(&b.split_once(' ').map(|x| x.1)));
    runs.dedup();
    runs.truncate(5);
    runs
}

pub fn user_unit_dir() -> Result<PathBuf, String> {
    dirs::config_dir()
        .map(|d| d.join("systemd").join("user"))
        .ok_or_else(|| "Cannot determine ~/.config directory".into())
}

/// Writes both files to `~/.config/systemd/user/`, reloads the user manager, then
/// enables and starts the timer. Returns the directory written to.
pub async fn install(
    conn: &Connection,
    generated: &GeneratedTimer,
    overwrite: bool,
) -> Result<String, String> {
    let dir = user_unit_dir()?;
    tokio::fs::create_dir_all(&dir)
        .await
        .map_err(|e| format!("Cannot create {}: {e}", dir.display()))?;

    let files = [
        (dir.join(&generated.service_name), &generated.service_content),
        (dir.join(&generated.timer_name), &generated.timer_content),
    ];
    if !overwrite {
        if let Some((path, _)) = files.iter().find(|(p, _)| p.exists()) {
            return Err(format!("{} already exists", path.display()));
        }
    }
    for (path, content) in &files {
        tokio::fs::write(path, content)
            .await
            .map_err(|e| format!("Cannot write {}: {e}", path.display()))?;
    }

    systemd::reload(conn).await?;
    systemd::enable_and_start(conn, &generated.timer_name).await?;
    Ok(dir.display().to_string())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn req(cron: &str, name: &str, exec: &str) -> TimerRequest {
        TimerRequest {
            cron: cron.into(),
            unit_name: name.into(),
            exec_path: exec.into(),
            description: None,
        }
    }

    #[test]
    fn generates_unit_pair() {
        let g = generate(&req("0 2 * * *", "backup.service", "/usr/local/bin/backup.sh --full")).unwrap();
        assert_eq!(g.service_name, "backup.service");
        assert_eq!(g.timer_name, "backup.timer");
        assert!(g.service_content.contains("ExecStart=/usr/local/bin/backup.sh --full\n"));
        assert!(g.timer_content.contains("OnCalendar=*-*-* 02:00:00\n"));
        assert!(g.timer_content.contains("Unit=backup.service\n"));
        assert!(g.timer_content.contains("WantedBy=timers.target\n"));
    }

    #[test]
    fn rejects_unsafe_input() {
        assert!(generate(&req("0 2 * * *", "backup", "backup.sh")).is_err());
        assert!(generate(&req("0 2 * * *", "../evil", "/bin/true")).is_err());
        assert!(generate(&req("0 2 * * *", "x", "/bin/true\nExecStartPost=/bin/sh")).is_err());
    }

    #[test]
    fn reboot_uses_startup_delay() {
        let g = generate(&req("@reboot", "hello", "/bin/true")).unwrap();
        assert!(g.timer_content.contains("OnStartupSec=1min\n"));
        assert!(!g.timer_content.contains("OnCalendar"));
    }

    /// Installs a throwaway timer in the real user manager, then removes it:
    /// `cargo test -- --ignored live`.
    #[tokio::test]
    #[ignore]
    async fn live_install_roundtrip() {
        let buses = systemd::Buses::default();
        let conn = buses.get(systemd::Scope::User).await.unwrap();
        let g = generate(&req("*/30 * * * *", "sdd-selftest", "/bin/true")).unwrap();
        install(conn, &g, true).await.unwrap();

        let timers = systemd::list_timers(conn, systemd::Scope::User).await.unwrap();
        let t = timers.iter().find(|t| t.name == "sdd-selftest.timer").cloned();

        systemd::control_user(conn, "sdd-selftest.timer", "stop").await.unwrap();
        systemd::control_user(conn, "sdd-selftest.timer", "disable").await.unwrap();
        let dir = user_unit_dir().unwrap();
        std::fs::remove_file(dir.join("sdd-selftest.timer")).unwrap();
        std::fs::remove_file(dir.join("sdd-selftest.service")).unwrap();
        systemd::reload(conn).await.unwrap();

        let t = t.expect("timer should be loaded after install");
        println!("{t:?}");
        assert_eq!(t.active_state, "active");
        // systemd reports the normalized form of "*:00/30".
        assert_eq!(t.on_calendar, ["*-*-* *:00,30:00"]);
        assert!(t.next_elapse_ms.is_some());
    }
}
